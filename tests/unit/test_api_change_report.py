OLD = '''# This file was automatically generated by SWIG.
raise RuntimeError("Declarations must never execute")
class Options:
    Enabled = 1
    def _get_width(self) -> "float":
        """Width of the item."""
    width = property(_get_width)
    def create(self, count: "int" = 1) -> "bool":
        """Create an item."""
    def obsolete(self):
        pass
'''
NEW = OLD.replace('Enabled = 1', 'Enabled = 2').replace('count: "int" = 1', 'count: "int" = 2')
NEW = NEW.replace('"""Create an item."""', '"""This is a preview and is not officially supported."""')
NEW = NEW.replace('    width = property(_get_width)', '    def _set_width(self, value: "float"):\n        pass\n    width = property(_get_width, _set_width)')
NEW = NEW.replace('def obsolete(self):', 'def replacement(self):') + '\nclass Added:\n    pass\n'


@pytest.fixture
def captures(tmp_path):
    def capture(name, source, namespace='fusion'):
        folder = tmp_path / name
        folder.mkdir()
        (folder / f'{namespace}.py').write_bytes(source.encode('utf-8'))
        return report.snapshot(folder, name)
    return capture


def test_reports_added_removed_signature_writability_enum_and_support(captures):
    before, after = captures('before', OLD), captures('after', NEW)
    changes = {c['symbol']: c for c in report.compare(before, after)['changes']}
    assert changes['adsk.fusion.Options.obsolete']['change'] == 'removed'
    assert changes['adsk.fusion.Options.replacement']['change'] == 'added'
    assert changes['adsk.fusion.Added']['change'] == 'added'
    width = changes['adsk.fusion.Options.width']
    assert width['before']['writable'] is False and width['after']['writable'] is True
    assert changes['adsk.fusion.Options.Enabled']['after']['literal'] == 2
    create = changes['adsk.fusion.Options.create']['after']['overloads'][0]
    assert create['signature']['arguments'][0]['default'] == '2'
    assert create['mentions_preview'] is True and create['mentions_unsupported'] is True


def test_unavailable_namespace_never_becomes_symbol_removal(captures, tmp_path):
    before = captures('before', OLD)
    folder = tmp_path / 'before'
    (folder / 'cam.py').write_text('class MissingNamespaceType:\n    pass\n', encoding='utf-8')
    before = report.snapshot(folder, 'before')
    after = captures('after', OLD)
    delta = report.compare(before, after)
    assert delta['namespaces_unavailable_in_after'] == ['adsk.cam']
    assert delta['changes'] == []
    reverse = report.compare(after, before)
    assert reverse['namespaces_unavailable_in_before'] == ['adsk.cam']
    assert reverse['changes'] == []


@pytest.mark.parametrize('mismatch', ['format', 'representation', 'namespace_scope'])
def test_incompatible_comparisons_are_refused(captures, mismatch):
    before, after = captures('before', OLD), captures('after', OLD)
    if mismatch == 'format':
        after['format'] = 'older-format'
    elif mismatch == 'representation':
        after['modules']['adsk.fusion']['representation'] = 'python'
    else:
        after['namespace_scope'].append('adsk.future')
        after['unavailable_namespaces'].append('adsk.future')
    after['content_sha256'] = report.content_hash(after)
    with pytest.raises(ValueError, match='format|representation|scopes'):
        report.compare(before, after)


def test_provenance_hashes_original_bytes_and_preserves_deployment_identity(tmp_path):
    folder = tmp_path / 'webdeploy/pre-production/abc123/Api/Python/packages/adsk'
    folder.mkdir(parents=True)
    raw = b'\xef\xbb\xbf' + OLD.replace('\n', '\r\n').encode('utf-8')
    (folder / 'fusion.py').write_bytes(raw)
    data = report.snapshot(folder, 'reported-build')
    assert data['modules']['adsk.fusion']['sha256'] == hashlib.sha256(raw).hexdigest()
    assert data['modules']['adsk.fusion']['path'] == str((folder / 'fusion.py').resolve())
    assert data['provenance']['webdeploy_path'] == {'channel': 'pre-production', 'directory_id': 'abc123'}
    assert data['provenance']['build_label'] == 'reported-build'
    assert data['provenance']['build_label_source'].startswith('caller-supplied')
    assert data['unavailable_namespaces'] == ['adsk.core', 'adsk.cam', 'adsk.drawing', 'adsk.sim', 'adsk.electron', 'adsk.volume']
    assert 'api_change_report.py' in data['provenance']['scanner_sha256']
    assert gen_api_surface.scan_module(str(folder / 'fusion.py'), 'fusion')[0]['fusion.Options'] == ['Enabled', 'create', 'obsolete', 'width']


def test_modified_snapshot_and_overwriting_are_refused(captures, tmp_path):
    data = captures('bindings', OLD)
    path = tmp_path / 'snapshot.json'
    report.write_json(path, data)
    original = path.read_bytes()
    with pytest.raises(FileExistsError):
        report.write_json(path, {})
    assert path.read_bytes() == original
    changed = copy.deepcopy(data)
    changed['modules']['adsk.fusion']['classes'].clear()
    with pytest.raises(ValueError, match='content hash'):
        report.compare(data, changed)
    loaded, provenance = report.load_snapshot(path)
    assert loaded == data
    assert provenance['sha256'] == hashlib.sha256(original).hexdigest()


