def test_helper_matches_and_checks_are_only_syntactic_candidates(captures, source_repo):
    before, after = captures('before', OLD), captures('after', NEW)
    data = report.add_impacts(report.compare(before, after), source_repo)
    width = next(c for c in data['changes'] if c['symbol'].endswith('.width'))
    assert width['candidate_tools'] == [{
        'tool': 'model_demo', 'classification': 'syntactic_candidate',
        'source_matches': [{'file': 'commands/mcpServer/tools/_demo.py', 'line': 2, 'via': 'local_import'}],
    }]
    mapping = data['impact_mapping']
    assert mapping['classification'] == 'syntactic_candidate'
    assert 'Empty matches do not prove absence of impact' in mapping['limitations']
    cases = mapping['candidate_acceptance_cases']['model_demo']
    assert cases['classification'] == 'syntactic_candidate'
    assert [c['kind'] for c in cases['cases']] == ['unit_test', 'live_row', 'eval_tool_mention']
    assert cases['cases'][0]['case'] == 'test_width_effect'
    assert 'tests/live/verify_acts_model.py' in mapping['source_sha256']
    assert 'model_unrelated' not in mapping['candidate_acceptance_cases']


def test_cli_diff_preserves_input_bytes_and_emits_provenance(captures, source_repo, tmp_path, capsys):
    before, after = captures('before', OLD), captures('after', NEW)
    a, b, output = (tmp_path / name for name in ('a.json', 'b.json', 'impact.json'))
    report.write_json(a, before)
    report.write_json(b, after)
    original = a.read_bytes(), b.read_bytes()
    assert report.main(['diff', str(a), str(b), '--repo', str(source_repo), '--out', str(output)]) == 0
    data = json.loads(output.read_text(encoding='utf-8'))
    assert data['before_snapshot']['path'] == str(a.resolve())
    assert data['after_snapshot']['modules']['adsk.fusion']['sha256'] == after['modules']['adsk.fusion']['sha256']
    assert data['summary'] == {'added': 2, 'removed': 1, 'changed': 3}
    assert (a.read_bytes(), b.read_bytes()) == original
    assert json.loads(capsys.readouterr().out)['output'] == str(output.resolve())


def test_python_overloads_setter_type_and_symbolic_constants_are_preserved(captures):
    source = '''class Demo:
    Enabled = _native.Demo_Enabled
    @overload
    def make(self, value: int): ...
    @overload
    def make(self, value: str): ...
    @property
    def width(self) -> float: ...
    @width.setter
    def width(self, value: float): ...
'''
    data = captures('python', source)
    cls = data['modules']['adsk.fusion']['classes']['adsk.fusion.Demo']
    assert data['modules']['adsk.fusion']['representation'] == 'python'
    assert len(cls['members']['make']['overloads']) == 2
    assert cls['members']['width']['setter_signature']['arguments'][0]['type'] == 'float'
    enabled = cls['members']['Enabled']
    assert enabled['expression'] == '_native.Demo_Enabled'
    assert enabled['literal_available'] is False


def test_property_assignment_controls_exposure_even_when_helpers_remain(captures):
    before = captures('before', NEW)
    readonly = NEW.replace('property(_get_width, _set_width)', 'property(fget=_get_width, fset=None)')
    after = captures('after', readonly)
    changes = report.compare(before, after)['changes']
    width = next(c for c in changes if c['symbol'] == 'adsk.fusion.Options.width')
    assert width['before']['writable'] is True and width['after']['writable'] is False
    assert width['after']['readable'] is True
    assert 'setter_signature' not in width['after']
    unexposed = captures('unexposed', NEW.replace('    width = property(_get_width, _set_width)\n', ''))
    removed = report.compare(before, unexposed)['changes']
    assert next(c for c in removed if c['symbol'].endswith('.width'))['change'] == 'removed'
